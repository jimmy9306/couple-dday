// 레이어 순서(아래→위): 몸(피부) → 신발 → 하의 → 상의 → 머리.
// 각 파츠는 24개의 16글자 문자열('#'=칠해짐)로 정의하고, gridFromRows로 변환해 사용.
import { gridFromRows } from './pixelGrid'

const EMPTY_ROW = '................'

function rows(overrides) {
  // overrides: { [rowIndex]: '16글자 문자열' } — 나머지 행은 빈 줄로 채움
  const out = Array.from({ length: 24 }, () => EMPTY_ROW)
  Object.entries(overrides).forEach(([i, str]) => {
    out[Number(i)] = str
  })
  return out
}

